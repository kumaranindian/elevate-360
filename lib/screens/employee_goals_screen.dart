  bool _isLoading = true;
  late String _employeeId;
  List<GoalModel> _goals = [];
  List<GoalModel> _availableGoals = [];
  
  @override
  void initState() {
    super.initState();
    _loadEmployeeData();
  }

  Future<void> _loadEmployeeData() async {
    try {
      // Get employee data using user account ID
      final employee = await EmployeeService.getEmployeeByUserAccountId(widget.userModel.uid);
      _employeeId = employee.id;
      
      await _loadGoals();
      await _loadAvailableGoals();
    } catch (e) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Error loading goals: $e')),
      );
    } finally {
      setState(() => _isLoading = false);
    }
  }

  Future<void> _loadGoals() async {
    try {
      final goals = await GoalService.getGoalsByEmployeeId(_employeeId);
      setState(() => _goals = goals);
    } catch (e) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Error loading goals: $e')),
      );
    }
  }

  Future<void> _loadAvailableGoals() async {
    try {
      // Get goals that are not assigned to this employee
      final allGoals = await GoalService.getAllGoals();
      setState(() {
        _availableGoals = allGoals.where((goal) => 
          goal.employeeId.isEmpty && // Unassigned goals
          goal.status == 'Not Started' // Only not started goals can be opted in
        ).toList();
      });
    } catch (e) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Error loading available goals: $e')),
      );
    }
  }

  Future<void> _optInForGoal(GoalModel goal) async {
    try {
      setState(() => _isLoading = true);

      // Create a new goal for the employee based on the template
      final employeeGoal = GoalModel(
        id: '', // Will be generated by Firebase
        employeeId: _employeeId,
        managerId: goal.managerId,
        categoryId: goal.categoryId,
        projectId: goal.projectId,
        title: goal.title,
        description: goal.description,
        goalType: goal.goalType,
        priority: goal.priority,
        weightage: goal.weightage,
        targetValue: goal.targetValue,
        currentValue: 0,
        unit: goal.unit,
        measurementMethod: goal.measurementMethod,
        startDate: DateTime.now(),
        dueDate: goal.dueDate,
        status: 'Not Started',
        progressPercentage: 0,
        isStretchGoal: goal.isStretchGoal,
        createdBy: goal.createdBy,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      await GoalService.createGoal(employeeGoal);
      await _loadGoals();
      await _loadAvailableGoals();

      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Successfully opted in for the goal')),
      );
    } catch (e) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Error opting in for goal: $e')),
      );
    } finally {
      setState(() => _isLoading = false);
    }
  }

  Future<void> _updateGoalProgress(GoalModel goal, double progress, String status) async {
    try {
      setState(() => _isLoading = true);

      // Calculate current value based on progress percentage
      final currentValue = goal.targetValue != null 
        ? (goal.targetValue! * progress / 100)
        : progress;

      // Create updated goal model
      final updatedGoal = GoalModel(
        id: goal.id,
        employeeId: goal.employeeId,
        managerId: goal.managerId,
        categoryId: goal.categoryId,
        projectId: goal.projectId,
        title: goal.title,
        description: goal.description,
        goalType: goal.goalType,
        priority: goal.priority,
        weightage: goal.weightage,
        targetValue: goal.targetValue,
        currentValue: currentValue,
        unit: goal.unit,
        measurementMethod: goal.measurementMethod,
        startDate: goal.startDate,
        dueDate: goal.dueDate,
        completionDate: status == 'Completed' ? DateTime.now() : null,
        status: status,
        progressPercentage: progress,
        isStretchGoal: goal.isStretchGoal,
        createdBy: goal.createdBy,
        approvedBy: goal.approvedBy,
        createdAt: goal.createdAt,
        updatedAt: DateTime.now(),
      );

      // Update goal in Firebase
      await GoalService.updateGoal(updatedGoal);
      await _loadGoals(); // Reload goals to update UI

      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: const Text('Goal updated successfully'),
          backgroundColor: AppTheme.successColor,
          behavior: SnackBarBehavior.floating,
        ),
      );
    } catch (e) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Error updating goal: $e'),
          backgroundColor: AppTheme.errorColor,
          behavior: SnackBarBehavior.floating,
        ),
      );
    } finally {
      setState(() => _isLoading = false);
    }
  }



