  List<GoalModel> _getFilteredGoals() {
    if (_selectedFilter == 'All') {
      return _goals;
    }
    return _goals.where((goal) => goal.status == _selectedFilter).toList();
  }

  Map<String, dynamic> _getGoalStats() {
    int notStarted = 0;
    int inProgress = 0;
    int completed = 0;
    int overdue = 0;
    double totalProgress = 0;

    for (var goal in _goals) {
      if (goal.isOverdue) {
        overdue++;
      }
      
      switch (goal.status) {
        case 'Not Started':
          notStarted++;
          break;
        case 'In Progress':
          inProgress++;
          break;
        case 'Completed':
          completed++;
          break;
      }

      totalProgress += goal.progressPercentage;
    }

    return {
      'Not Started': notStarted,
      'In Progress': inProgress,
      'Completed': completed,
      'Overdue': overdue,
      'Average Progress': _goals.isEmpty ? 0 : (totalProgress / _goals.length).round(),
    };
  }

  Color _getStatusColor(String status) {
    switch (status.toLowerCase()) {
      case 'not started':
        return AppTheme.textSecondary;
      case 'in progress':
        return AppTheme.primaryColor;
      case 'completed':
        return AppTheme.successColor;
      case 'overdue':
        return AppTheme.errorColor;
      default:
        return AppTheme.textSecondary;
    }
  }

  Color _getPriorityColor(String priority) {
    switch (priority.toLowerCase()) {
      case 'high':
        return AppTheme.errorColor;
      case 'medium':
        return AppTheme.warningColor;
      case 'low':
        return AppTheme.successColor;
      default:
        return AppTheme.textSecondary;
    }
  }
